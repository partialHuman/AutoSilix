"""Report generation in Markdown, JSON, and CSV formats."""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path
from typing import Any


class ReportGenerator:
    """Generates execution summaries and PPA reports across multiple formats."""

    @staticmethod
    def generate_markdown(manifest_data: dict[str, Any]) -> str:
        """Create a human-readable GitHub-flavored Markdown report."""
        run_id = manifest_data.get("run_id", "unknown")
        design = manifest_data.get("design_name", "unknown")
        status = manifest_data.get("status", "UNKNOWN")
        start = manifest_data.get("start_time", "N/A")
        end = manifest_data.get("end_time", "N/A")
        dur = manifest_data.get("duration_seconds", 0.0)

        env = manifest_data.get("environment", {})
        git_commit = manifest_data.get("git_commit") or "Not a git repo or uncommitted"
        git_dirty = manifest_data.get("git_dirty")
        dirty_str = " (Dirty Working Tree)" if git_dirty else ""

        status_badge = "🟢 **PASS**" if status == "PASS" else "🔴 **FAIL**"

        lines = [
            "# AutoSilix Implementation Report",
            "",
            f"**Design**: `{design}` | **Run ID**: `{run_id}` | **Status**: {status_badge}",
            "",
            "## 1. Run Provenance & Environment",
            "",
            f"- **Start Time (UTC)**: `{start}`",
            f"- **End Time (UTC)**: `{end}`",
            f"- **Total Duration**: `{dur:.2f}s`",
            f"- **Git Revision**: `{git_commit}{dirty_str}`",
            f"- **Operating System**: `{env.get('os', 'unknown')}`",
            f"- **Python Version**: `{env.get('python_version', 'unknown')}`",
            f"- **Configuration Hash**: `{manifest_data.get('config_hash', 'N/A')}`",
            "",
            "## 2. Stage Execution Summary",
            "",
            "| Stage | State | Duration (s) | Exit Code | Log File | Error Summary |",
            "|---|---|---|---|---|---|",
        ]

        stages = manifest_data.get("stages", {})
        for name, s in stages.items():
            st = s.get("state", "UNKNOWN")
            d = s.get("duration_seconds", 0.0)
            code = s.get("exit_code") if s.get("exit_code") is not None else "-"
            log = s.get("log_file") or "-"
            err = s.get("error_summary") or "-"
            lines.append(f"| `{name}` | `{st}` | {d:.2f} | `{code}` | `{Path(log).name if log != '-' else '-'}` | {err} |")

        lines.extend([
            "",
            "## 3. Extracted PPA Metrics",
            "",
            "| Metric Name | Value | Unit | Stage | Source File |",
            "|---|---|---|---|---|",
        ])

        metrics = manifest_data.get("metrics", {})
        if metrics:
            for m_name, m_data in sorted(metrics.items()):
                val = m_data.get("value")
                unit = m_data.get("unit") or "-"
                stage = m_data.get("stage", "-")
                src = Path(m_data.get("source_file", "-")).name
                lines.append(f"| `{m_name}` | **{val}** | {unit} | `{stage}` | `{src}` |")
        else:
            lines.append("| *No metrics extracted* | - | - | - | - |")

        lines.extend([
            "",
            "## 4. Verification Scope & Limitations Disclaimer",
            "",
            "> [!IMPORTANT]",
            "> A successful workflow run and generated layout stream (GDSII) do **not** constitute tape-out readiness.",
            "> Fabrication acceptance requires signoff-grade DRC/LVS rule decks, exhaustive multi-corner STA,",
            "> electromigration, and foundry physical verification reviews.",
            "",
            "---",
            "*Generated by AutoSilix v0.1.0 — From RTL to layout, reproducibly.*",
        ])

        return "\n".join(lines) + "\n"

    @staticmethod
    def generate_json_summary(manifest_data: dict[str, Any]) -> str:
        """Create a formatted JSON string summary of the run and metrics."""
        summary = {
            "run_id": manifest_data.get("run_id"),
            "design_name": manifest_data.get("design_name"),
            "status": manifest_data.get("status"),
            "duration_seconds": manifest_data.get("duration_seconds"),
            "config_hash": manifest_data.get("config_hash"),
            "stages": {
                k: {"state": v.get("state"), "duration_seconds": v.get("duration_seconds")}
                for k, v in manifest_data.get("stages", {}).items()
            },
            "metrics": {
                k: {"value": v.get("value"), "unit": v.get("unit")}
                for k, v in manifest_data.get("metrics", {}).items()
            },
        }
        return json.dumps(summary, indent=2)

    @staticmethod
    def generate_csv_metrics(manifest_data: dict[str, Any]) -> str:
        """Export metrics as CSV string."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["run_id", "design_name", "metric_name", "value", "unit", "stage", "source_file"])

        run_id = manifest_data.get("run_id", "")
        design = manifest_data.get("design_name", "")

        for m_name, m_data in sorted(manifest_data.get("metrics", {}).items()):
            writer.writerow([
                run_id,
                design,
                m_name,
                m_data.get("value"),
                m_data.get("unit") or "",
                m_data.get("stage") or "",
                m_data.get("source_file") or "",
            ])

        return output.getvalue()

    @classmethod
    def save_all_reports(cls, manifest_data: dict[str, Any], run_dir: Path) -> dict[str, Path]:
        """Generate and save Markdown, JSON, and CSV reports inside run_dir."""
        md_text = cls.generate_markdown(manifest_data)
        json_text = cls.generate_json_summary(manifest_data)
        csv_text = cls.generate_csv_metrics(manifest_data)

        md_path = run_dir / "reports" / "summary.md"
        json_path = run_dir / "metrics" / "summary.json"
        csv_path = run_dir / "metrics" / "metrics.csv"

        md_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.parent.mkdir(parents=True, exist_ok=True)

        md_path.write_text(md_text, encoding="utf-8")
        json_path.write_text(json_text, encoding="utf-8")
        csv_path.write_text(csv_text, encoding="utf-8")

        return {
            "markdown": md_path,
            "json": json_path,
            "csv": csv_path,
        }
